"""Regenerate records/index.html: links to core docs, method pages, every run (with key metrics), results and figures."""
import glob
import html
import json
import os

from mu import RECORDS_DIR

KEYS = ["acc_forget", "acc_retain", "acc_test", "acc_val", "mia.mia_acc", "mia.mia_auc", "avg_gap", "unlearn_time_s", "train_time_s", "peak_mem_gb"]


def _get(d, key):
    for k in key.split("."):
        if not isinstance(d, dict) or k not in d:
            return ""
        d = d[k]
    return f"{d:.2f}" if isinstance(d, float) else d


def main():
    runs = []
    for cfg_path in sorted(glob.glob(os.path.join(RECORDS_DIR, "runs", "*", "config.json"))):
        d = os.path.dirname(cfg_path)
        cfg = json.load(open(cfg_path))
        met = json.load(open(os.path.join(d, "metrics.json"))) if os.path.exists(os.path.join(d, "metrics.json")) else {}
        runs.append((os.path.basename(d), cfg, met))

    rows = []
    for rid, cfg, met in runs:
        cells = [f'<a href="runs/{rid}/summary.md">{html.escape(rid)}</a>' if met else html.escape(rid),
                 cfg.get("kind", ""), cfg.get("method", ""), cfg.get("scenario", ""), cfg.get("seed", ""), cfg.get("status", ""),
                 cfg.get("start_time", ""), cfg.get("end_time", "")] + [_get(met, k) for k in KEYS] + \
                [f'<a href="runs/{rid}/config.json">cfg</a> <a href="runs/{rid}/history.csv">hist</a> <a href="runs/{rid}/stdout.log">log</a>']
        rows.append("<tr>" + "".join(f"<td>{c}</td>" for c in cells) + "</tr>")
    head = ["run_id", "kind", "method", "scenario", "seed", "status", "start", "end"] + KEYS + ["files"]

    def file_list(sub, pat="*"):
        fs = sorted(glob.glob(os.path.join(RECORDS_DIR, sub, pat)))
        return "<ul>" + "".join(f'<li><a href="{sub}/{os.path.basename(f)}">{os.path.basename(f)}</a></li>' for f in fs) + "</ul>" if fs else "<p>(none yet)</p>"

    page = f"""<!DOCTYPE html><html><head><meta charset="utf-8"><title>Machine Unlearning - Experiment Index</title>
<style>body{{font-family:sans-serif;margin:2em}}table{{border-collapse:collapse;font-size:12px}}td,th{{border:1px solid #ccc;padding:3px 6px}}th{{background:#eee}}</style></head><body>
<h1>Machine Unlearning (CIFAR-10 / ResNet-18) - Experiment Index</h1>
<p>Auto-generated by <code>scripts/build_index.py</code>. Resume order: JOURNAL.md -> 00_plan.md -> this page.</p>
<h2>Core documents</h2><ul>
<li><a href="00_plan.md">00_plan.md</a> - plan, setup, hyperparameters with sources</li>
<li><a href="JOURNAL.md">JOURNAL.md</a> - chronological log</li>
<li><a href="README.md">README.md</a> - record conventions</li>
<li><a href="conversation_log.md">conversation_log.md</a> - full user/assistant conversation</li></ul>
<h2>Methods</h2>{file_list("methods", "*.md")}
<h2>Runs ({len(runs)})</h2><table><tr>{"".join(f"<th>{h}</th>" for h in head)}</tr>{"".join(rows)}</table>
<h2>Results</h2>{file_list("results")}
<h2>Figures</h2>{file_list("figures")}
</body></html>"""
    with open(os.path.join(RECORDS_DIR, "index.html"), "w") as f:
        f.write(page)
    print(f"index.html: {len(runs)} runs")


if __name__ == "__main__":
    main()
