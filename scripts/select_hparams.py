"""Pick final hyperparameters from the pilot: per (scenario type, method, mask), the pilot run with the lowest sel_gap
(sel_gap uses forget/retain/VAL accuracy + MIA with val negatives; no test data). S1 pilot -> 'class', S2k359p30 pilot -> 'subset_random'.
Only BN-in-train-mode runs are eligible for the main grid (bn_mode=frozen is an ablation).
Writes configs/final_hparams.yaml: {method: {mask: {scenario_type: {overrides..., _source_run, _sel_gap}}}}.
"""
import json
import os

import pandas as pd
import yaml

from mu import RECORDS_DIR, ROOT

SC_TYPE = {"S1c0": "class", "S2k359p30": "subset_random"}


def main():
    df = pd.read_csv(os.path.join(RECORDS_DIR, "results", "all_runs.csv"))
    pil = df[df["tag"].fillna("").str.startswith("pilot") & ~df["tag"].fillna("").str.contains("bnfrozen") & df["scenario"].isin(SC_TYPE)]
    defaults = yaml.safe_load(open(os.path.join(ROOT, "configs", "methods.yaml")))
    out = {}
    for (sc, method, mask), g in pil.groupby(["scenario", "method", "mask"]):
        best = g.loc[g["sel_gap"].idxmin()]
        hp = json.load(open(os.path.join(RECORDS_DIR, "runs", best["run_id"], "config.json")))["hparams"]
        st = SC_TYPE[sc]
        base = {**defaults[method].get("common", {}), **(defaults[method].get(st) or {})}
        ov = {k: v for k, v in hp.items() if k != "stop_forget_acc" and base.get(k) != v}
        ov.update(_source_run=best["run_id"], _sel_gap=round(float(best["sel_gap"]), 3), _avg_gap=round(float(best["avg_gap"]), 3),
                  _n_pilot_runs=int(len(g)))
        out.setdefault(method, {}).setdefault(mask, {})[st] = ov
    path = os.path.join(ROOT, "configs", "final_hparams.yaml")
    with open(path, "w") as f:
        f.write("# AUTO-GENERATED by scripts/select_hparams.py from the pilot (lowest sel_gap). Overrides on top of configs/methods.yaml.\n")
        yaml.safe_dump(out, f, sort_keys=True)
    print(open(path).read())


if __name__ == "__main__":
    main()
