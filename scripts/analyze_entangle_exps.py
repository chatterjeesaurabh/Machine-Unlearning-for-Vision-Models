"""Builds records/results/entanglement_experiments.md (+ .csv) from the 'entpart' (Exp 1) and 'entseq'/'entseqfinal' (Exp 2) runs.
Re-run any time; it reports whatever runs exist (n = number of seeds found)."""
import json
import os

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd

from mu import RECORDS_DIR
from mu.entangle_runs import prep_ent

RES, FIG = os.path.join(RECORDS_DIR, "results"), os.path.join(RECORDS_DIR, "figures")
SCEN = ["S1c0", "S2k359p10", "S2k359p30", "S2k359p50"]
PARTS = ["low", "medium", "high"]
METHODS = ["GA", "GAGD", "TS", "RLrand", "RLbnd"]
NAME = {"GA": "M1 Gradient Ascent", "GAGD": "M2 GA + Descent", "TS": "M3a Teacher-Student", "RLrand": "M3b-R Random Relabeling",
        "RLbnd": "M3b-B Boundary Relabeling"}
CONF = {"GA": ("G3: mixed BN, lr 3e-4, 10 ep, iter stop every 2 at max(Retrain forget acc, 1%)",
               "G3-S2: mixed BN, lr 1e-4, 10 ep, iter stop at Retrain forget acc"),
        "GAGD": ("D1: lr 0.01, beta 0.99, 5 ep, clip 1", "D1-S2: lr 0.01, beta 0.999, 5 ep, clip 1"),
        "TS": ("T1: T 4, alpha 0.1, gamma 1, 3 ep, msteps 2, forget bs 43 (=128/3), retain bs 128",
               "T4-best S2: T 4, alpha 0.1, gamma 0.1, 3 ep, msteps 2, forget bs 21 (S2-50: 43), retain bs 64"),
        "RLrand": ("R1: lr 0.005, 10 ep", "R1-S2: lr 0.02, 10 ep"),
        "RLbnd": ("C1-mix: logit2 labels, lr 1e-3, 10 ep, retain pass, mixed BN", "C0: FGSM eps 0.1, lr 1e-5, 10 ep (no good S2 config)")}
# one-shot runs (whole forget set at once, same configuration) for comparison with Exp 2
ONESHOT = {"GA": ("imp5_gamix", "imp5_gamix"), "GAGD": ("", ""), "TS": ("", "imp3_tsill"),
           "RLrand": ("", ""), "RLbnd": ("imp5_bndlogit2mix", "")}
ONESHOT_SC = {("TS", "S2k359p50"): "imp4_tsill_fbs128"}  # S2-50 confirmed TS config uses forget bs 128
COLS = ["acc_forget", "acc_retain", "acc_test", "mia_acc", "avg_gap"]
COLS1 = ["acc_forget", "acc_excluded", "acc_retain", "acc_test", "mia_acc", "avg_gap"]


def fmt(m, s, n):
    return "-" if pd.isna(m) else (f"{m:.2f} ± {s:.2f}" if n > 1 and not pd.isna(s) else f"{m:.2f}")


def main():
    df = prep_ent(pd.read_csv(os.path.join(RES, "all_runs.csv")))
    parts_info = json.load(open(os.path.join(RES, "entangle_partitions.json")))
    L = ["# Entanglement experiments (Evaluation III)", "",
         "Auto-generated by `scripts/analyze_entangle_exps.py` (re-run to refresh). Runs: tags `entpart`, `entseq`, `entseqfinal`; batches",
         "`outputs/ent_batch_s{0,1,2}.sh` (generator `scripts/entangle_grid.py`); partitions `scripts/make_entangle_partitions.py`.", "",
         "## Design",
         "- **Entanglement score** (slide 14): for every forget sample, the mean Euclidean distance to its k = 50 nearest RETAIN samples in the",
         "  Original model's 512-d penultimate (avgpool) feature space (no augmentation). Smaller distance = more entangled.",
         "- The forget set is ranked by this score and split into equal thirds: **low** (largest distances), **medium**, **high** (smallest).",
         "- **Exp 1 - individual partitions:** each method unlearns each partition separately, starting from the Original model.",
         "  - **S2 (subset forgetting), RUM protocol (tag `entpart`):** forget = one partition, retain = all other training data (the other",
         "    two partitions included). A Retrain reference is trained per partition (182 epochs, same recipe as all references).",
         "  - **S1 (single-class forgetting), corrected setup (tag `entpart2`, 2026-10-30):** forget = one partition, retain = the normal S1",
         "    retain set (no airplane). The other two partitions are excluded from both sets (not used during unlearning); their accuracy",
         "    is reported as `excluded` (the other 3000 airplanes). Reference = the normal S1 Retrain evaluated on the partition. (The first",
         "    S1 run, with the other partitions in the retain set, turned S1 into a subset-forgetting problem and is superseded.)",
         "- **Exp 2 - sequential (low -> medium -> high):** step 1 forget = low (medium + high in the retain set), step 2 forget = medium",
         "  (high in the retain set), step 3 forget = high (no partition in the retain set). Each step starts from the previous step's",
         "  model (for Teacher-Student / Boundary Relabeling the teacher / neighbour model and for WS the saliency mask are taken from the",
         "  model at the start of the step). The final model is evaluated on the WHOLE forget set against the base-scenario Retrain and",
         "  compared with unlearning the whole forget set at once (one-shot) with the same configuration.",
         "- 4 scenarios (S1 class 0; S2 10 / 30 / 50% of classes 3,5,9) x 3 seeds x 5 methods x {no mask, WS 0.5}.",
         "- avg_gap = mean |metric - Retrain| over forget acc, retain acc, test acc and MIA acc (lower = closer to Retrain).", "",
         "## Configurations (best per method, `records/results/method_comparison.md`)", "", "| method | S1 (class) | S2 (subset) |", "|---|---|---|"]
    L += [f"| {NAME[m]} | {CONF[m][0]} | {CONF[m][1]} |" for m in METHODS]
    L += ["", "Common: SGD momentum 0.9, weight decay 5e-4, batch 256 (unless stated), crop + flip augmentation, bf16. WS = Gradient based",
          "Weight Saliency mask ratio 0.5 with the same hyperparameters. Teacher-Student forget batch scaled by 1/3 because a partition is",
          "1/3 of the forget set (same number of forget updates per epoch as the confirmed configuration).", "",
          "## Partitions (k = 50, mean distance to retain; global ES of partition vs its retain set, RUM formula)", "",
          "| scenario | seed | low: n / mean dist / ES | medium | high |", "|---|---|---|---|---|"]
    for key, v in parts_info.items():
        sc, s = key.split("__")
        cell = lambda p: f"{v['partitions'][p]['n']} / {v['partitions'][p]['dist_mean']:.3f} / {v['partitions'][p]['global_ES_vs_retain']:.1f}"
        L.append(f"| {sc} | {s[1:]} | {cell('low')} | {cell('medium')} | {cell('high')} |")

    # ---------------- Exp 1
    e1 = df[df["tag"] == "entpart"]
    ref = df[(df["method"] == "retrain") & df["part"].isin(PARTS)]
    L += ["", "## Exp 1 - each partition unlearned individually", ""]
    rows = []
    for sc in SCEN:
        L += [f"### {sc}", "", "| method | WS | partition | n | forget (partition) | excluded (other airplanes, S1 only) | retain | test | MIA | avg_gap |", "|---|---|---|---|---|---|---|---|---|---|"]
        for p in PARTS:
            r = ref[(ref["base"] == sc) & (ref["part"] == p)]
            if len(r):
                L.append(f"| Retrain | | {p} | {len(r)} | " + " | ".join(fmt(r[c].mean(), r[c].std(), len(r)) for c in COLS1[:5]) + " | 0 |")
        for p in PARTS:
            r = e1[(e1["base"] == sc) & (e1["part"] == p) & (e1["method"] == "original")]
            if len(r):
                L.append(f"| Original | | {p} | {len(r)} | " + " | ".join(fmt(r[c].mean(), r[c].std(), len(r)) for c in COLS1) + " |")
        for m in METHODS:
            for mask in ("none", "saliency"):
                g = {p: e1[(e1["base"] == sc) & (e1["part"] == p) & (e1["method"] == m) & (e1["mask"] == mask)] for p in PARTS}
                for p in PARTS:
                    r = g[p]
                    if len(r):
                        L.append(f"| {NAME[m]} | {'yes' if mask == 'saliency' else ''} | {p} | {len(r)} | " + " | ".join(fmt(r[c].mean(), r[c].std(), len(r)) for c in COLS1) + " |")
                        rows.append({"scenario": sc, "method": m, "mask": mask, "partition": p, **{c: r[c].mean() for c in COLS1}})
        L.append("")
    t1 = pd.DataFrame(rows)
    if len(t1):
        t1.to_csv(os.path.join(RES, "entanglement_exp1.csv"), index=False)
        L += ["### Exp 1 summary: avg_gap by partition (lower = closer to Retrain) and trend low -> high", "",
              "Original = no unlearning (the gap that has to be closed); Retrain forget acc per partition shows how much the partition is",
              "still predicted when it is NOT trained on (low-entangled samples are the least predictable from the retain data).", "",
              "| scenario | method | WS | low | medium | high | high - low |", "|---|---|---|---|---|---|---|"]
        for sc in SCEN:
            o = e1[(e1["base"] == sc) & (e1["method"] == "original")].groupby("part")["avg_gap"].mean().reindex(PARTS)
            rf = ref[ref["base"] == sc].groupby("part")["acc_forget"].mean().reindex(PARTS)
            if o.notna().all():
                L.append(f"| {sc} | Original (no unlearning) | | {o['low']:.2f} | {o['medium']:.2f} | {o['high']:.2f} | {o['high'] - o['low']:+.2f} |")
            if rf.notna().all():
                L.append(f"| {sc} | (Retrain forget acc on partition) | | {rf['low']:.1f} | {rf['medium']:.1f} | {rf['high']:.1f} | |")
        for (sc, m, mask), g in t1.groupby(["scenario", "method", "mask"], sort=False):
            v = g.set_index("partition")["avg_gap"].reindex(PARTS)
            L.append(f"| {sc} | {NAME[m]} | {'yes' if mask == 'saliency' else ''} | {v['low']:.2f} | {v['medium']:.2f} | {v['high']:.2f} | {v['high'] - v['low']:+.2f} |")
        fig, axes = plt.subplots(1, len(SCEN), figsize=(5 * len(SCEN), 4), squeeze=False)
        for ax, sc in zip(axes[0], SCEN):
            for i, m in enumerate(METHODS):
                for mask, ls in (("none", "-"), ("saliency", "--")):
                    v = t1[(t1["scenario"] == sc) & (t1["method"] == m) & (t1["mask"] == mask)].set_index("partition")["avg_gap"].reindex(PARTS)
                    if v.notna().any():
                        ax.plot(PARTS, v.values, ls, marker="o", color=plt.cm.tab10(i), label=f"{m}{' +WS' if mask == 'saliency' else ''}")
            ax.set_title(sc, fontsize=10)
            ax.set_xlabel("entanglement partition")
            ax.set_ylabel("avg_gap to partition Retrain")
        axes[0][0].legend(fontsize=6)
        fig.tight_layout()
        fig.savefig(os.path.join(FIG, "fig_entangle_exp1.png"), dpi=130)
        plt.close(fig)
        L += ["", "Figure: `records/figures/fig_entangle_exp1.png`."]

    # ---------------- Exp 2
    fin = df[df["tag"] == "entseqfinal"].copy()
    fin["method_"] = fin["method"].str.replace("seqfinal_", "").str.replace("_WS", "")
    fin["mask_"] = np.where(fin["method"].str.endswith("_WS"), "saliency", "none")
    steps = df[df["tag"] == "entseq"]
    L += ["", "## Exp 2 - sequential unlearning low -> medium -> high, final model on the whole forget set", ""]
    rows2 = []
    for sc in SCEN:
        r = df[(df["scenario"] == sc) & (df["method"] == "retrain") & (df["tag"] == "")]
        L += [f"### {sc}", "", "| method | WS | mode | n | forget | retain | test | MIA | avg_gap |", "|---|---|---|---|---|---|---|---|---|"]
        if len(r):
            L.append(f"| Retrain | | | {len(r)} | " + " | ".join(fmt(r[c].mean(), r[c].std(), len(r)) for c in COLS[:4]) + " | 0 |")
        for m in METHODS:
            for mask in ("none", "saliency"):
                s = fin[(fin["scenario"] == sc) & (fin["method_"] == m) & (fin["mask_"] == mask)]
                otag = ONESHOT_SC.get((m, sc), ONESHOT[m][0 if sc.startswith("S1") else 1])
                o = df[(df["scenario"] == sc) & (df["method"] == m) & (df["mask"] == mask) & (df["tag"].str.fullmatch(otag) if otag else df["tag"] == "")]
                for mode, x in (("sequential", s), ("one-shot", o)):
                    if len(x):
                        L.append(f"| {NAME[m]} | {'yes' if mask == 'saliency' else ''} | {mode} | {len(x)} | " + " | ".join(fmt(x[c].mean(), x[c].std(), len(x)) for c in COLS) + " |")
                        rows2.append({"scenario": sc, "method": m, "mask": mask, "mode": mode, **{c: x[c].mean() for c in COLS}})
        L.append("")
        st = steps[steps["base"] == sc]
        if len(st):
            L += [f"Per-step forget accuracy on the step's own partition ({sc}; mean over seeds):", "",
                  "| method | WS | step 1 (low) | step 2 (medium) | step 3 (high) |", "|---|---|---|---|---|"]
            for m in METHODS:
                for mask in ("none", "saliency"):
                    v = st[(st["method"] == m) & (st["mask"] == mask)].groupby("part")["acc_forget"].mean().reindex(["seq1", "seq2", "seq3"])
                    if v.notna().any():
                        L.append(f"| {NAME[m]} | {'yes' if mask == 'saliency' else ''} | " + " | ".join("-" if pd.isna(x) else f"{x:.2f}" for x in v.values) + " |")
            L.append("")
    if rows2:
        pd.DataFrame(rows2).to_csv(os.path.join(RES, "entanglement_exp2.csv"), index=False)
    open(os.path.join(RES, "entanglement_experiments.md"), "w").write("\n".join(L) + "\n")
    print(f"entanglement_experiments.md written ({len(e1)} exp1 runs, {len(fin)} exp2 final evals)")


if __name__ == "__main__":
    main()
